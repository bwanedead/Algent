FIPS_TO_ISO2: dict[str, str] = {a: b for a, b in (p.split() for p in _PAIRS.replace("\n", "").split(",") if p.strip())}


def iso2(fips: str) -> str:
    return FIPS_TO_ISO2.get((fips or "").strip().upper(), "")
